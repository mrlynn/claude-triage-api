/**
 * The Tutor: timed cram sessions on the Messages API, built from the course.
 *
 * Four small structured calls rather than one long conversation, because each
 * one has a different job and a different definition of done:
 *
 *   buildPlan      the sequence — outline only, so it is fast and cheap
 *   prepareLesson  one session's brief, drill and exercise, on demand
 *   reviewAttempt  a verdict against that exercise's rubric
 *   hintForAttempt one step less stuck, without the answer
 *
 * Nothing is stored. The learner's browser holds the plan and hands back the
 * parts each call needs, which is why the routes bound every field they accept.
 *
 * The corpus (generated by `npm run sync:storefront`) is the frozen first
 * system block with the cache breakpoint on it. It is ~33k tokens and
 * identical on every lesson and every review from every learner, so within a
 * five-minute window repeat calls pay cache-read rates for it — Lab 5, applied.
 * See `planSystem` for why the plan call is the exception.
 *
 * Every output goes through `tutorPolicy.ts` before it leaves this file.
 */

/** The model and per-call ceilings live in callLimits.ts, where cost.ts can price them. */
export { TUTOR_MODEL };

/** Who pays for a Tutor call. The house key unless the route says otherwise. */
export interface CallOptions {
  client?: Anthropic;
  /** Told what the call cost as soon as it returns, before validation can throw. The route settles credit with it. */
  onSpend?: (micros: number, response: { usage: Anthropic.Usage; model: string; stop_reason: string | null }) => void;
}

export const CORPUS = corpus;
/** The lab an authored mistake belongs to, or undefined for an id the Tutor never planted. */
export const mistakeLab = (id: string): string | undefined => MISTAKES.get(id)?.labId;
export const KNOWN_IDS: ReadonlySet<string> = new Set(corpus.map((d) => d.id));

/**
 * The authored mistakes, by id. Starters may only plant these, and the review
 * and hint routes look up what an echoed id means here rather than trusting
 * the page to say. They are NOT in the cached corpus prefix: only the lesson
 * call for a session whose labs have some sees them, in its own message.
 */
const MISTAKES: ReadonlyMap<string, MistakeItem & { labId: string }> = new Map(
  corpus.flatMap((d) => d.mistakes.map((m): [string, MistakeItem & { labId: string }] => [m.id, { ...m, labId: d.id }])),
);

/**
 * The rate card, generated from src/config.ts. "Never invent prices" was already a rule, and a
 * live Lab 7 starter still priced claude-sonnet-5 at $3/$15 against a catalog that says $2/$10:
 * a rule about a fact is weaker than the fact. It sits in the cached prefix, so it costs a cache
 * write per deploy and nothing per call.
 */
const RATE_CARD = `Model prices, per million tokens, from the course's pricing table. Wherever a price appears in anything you write, including code, use these exactly:\n${Object.entries(
  PRICING_BY_MODEL,
)
  .map(
    ([id, p]) =>
      `- ${id}: $${p.inputPerMTok} input, $${p.outputPerMTok} output; cache writes ${p.cacheWriteMultiplier}x input, cache reads ${p.cacheReadMultiplier}x input, batch ${p.batchMultiplier}x`,
  )
  .join("\n")}`;

const ROLE = `You are the Tutor for "Claude Triage API", a hands-on course on the Anthropic Messages API. You run focused, timed cram sessions: a learner has a fixed amount of time and wants to be able to use the Messages API as a developer by the end of it.

Rules that apply to every task:
- Teach ONLY from the course documents below. Each has an id such as "lab-2" or "guide-tools". Whenever an output field asks for a lab id, use one of those ids exactly.
- If the learner asks for something the documents do not cover, say so in the field provided for gaps. Never invent API parameters, SDK methods, prices, or limits.
- Prefer the concrete: request bodies, response fields, stop reasons, event names, and the failure a developer will actually hit.
- Be brief. The learner is on a clock.

${RATE_CARD}

The course documents follow.`;

const DOCS = corpus
  .map(
    (d) =>
      `<doc id="${d.id}" title="${d.title}">\n${
        d.objectives.length ? `Objectives:\n${d.objectives.map((o) => `- ${o}`).join("\n")}\n\n` : ""
      }${d.body}\n</doc>`,
  )
  .join("\n\n");

function system(): Anthropic.TextBlockParam[] {
  return [{ type: "text", text: `${ROLE}\n\n${DOCS}`, cache_control: { type: "ephemeral" } }];
}

/**
 * The plan is sequenced from titles and objectives, not prose — and it gets
 * the index rather than the corpus, uncached, because of how caching actually
 * behaves here.
 *
 * The structured-output schema is part of the cached prefix, so the three
 * calls do not share one cache entry: each schema has its own. Measured on
 * this route: a second lesson or review reads ~33k tokens from cache and costs
 * roughly a quarter of the first. A plan is built once per learner, so a cache
 * write on it is a 25% surcharge on a read that never comes. Lab 5's rule —
 * cache what repeats — applied to the call that does not.
 */
const INDEX = corpus
  .map((d) => `- ${d.id}: ${d.title}${d.objectives.length ? `\n${d.objectives.map((o) => `    - ${o}`).join("\n")}` : ""}`)
  .join("\n");

function planSystem(): Anthropic.TextBlockParam[] {
  return [
    {
      type: "text",
      text: `${ROLE.replace("The course documents follow.", "The course index follows: document ids, titles and objectives.")}\n\n${INDEX}`,
    },
  ];
}

const LEVEL_TEXT: Record<Intake["level"], string> = {
  new: "new to the Anthropic API (has written code, never called Claude)",
  some: "has made a few Claude API calls but not built anything real",
  shipped: "has shipped something on the API and wants depth and production judgment",
};

export interface CallMeta {
  model: string;
  costUsd: number;
  cacheReadTokens: number;
  dropped: string[];
}

/**
 * Called on every response the moment it arrives, before the output is
 * validated: a reply that fails validation was still billed, and the spend
 * counter should say so.
 */
function spend(
  response: { usage: Anthropic.Usage; model: string; stop_reason: string | null },
  onSpend?: CallOptions["onSpend"],
): Omit<CallMeta, "dropped"> {
  const micros = costMicros(response.usage, response.model);
  recordSpend("tutor", micros);
  onSpend?.(micros, response);
  return {
    model: response.model,
    costUsd: microsToUsd(micros),
    cacheReadTokens: response.usage.cache_read_input_tokens ?? 0,
  };
}

/**
 * `messages.parse()` without the throw. When the JSON does not parse — which is exactly what a turn cut off at
 * `max_tokens` produces — the SDK throws, and the thrown error carries no usage. So a truncated lesson reached the
 * learner as "could not complete" instead of "ran out of room", and the tokens it burned never reached `onSpend`:
 * the house paid for a call the credit meter never saw. Create the message, let `spend` record it, then parse.
 */
async function parseCall<P extends Parameters<Anthropic["messages"]["parse"]>[0]>(
  client: Anthropic,
  params: P,
): Promise<Anthropic.Message & { parsed_output: ParsedOutput<P> | null }> {
  const message = await client.messages.create({ ...params, stream: false });
  const text = message.content.find((block) => block.type === "text")?.text;
  let parsed: ParsedOutput<P> | null = null;
  if (text !== undefined && message.stop_reason !== "max_tokens") {
    try {
      // The param type widens the format to plain JSON Schema; every call here passes zodOutputFormat, which parses.
      const format = params.output_config?.format as unknown as { parse(content: string): unknown } | undefined;
      parsed = (format?.parse(text) ?? null) as ParsedOutput<P> | null;
    } catch {
      /* requireParsed turns a null into the right TutorError */
    }
  }
  return { ...message, parsed_output: parsed };
}

type ParsedOutput<P> = P extends { output_config?: { format?: { parse(content: string): infer T } | null } | null } ? T : never;

/** `parsed_output` is typed and can still be null — usually a truncated turn. */
function requireParsed<T>(response: { parsed_output: T | null; stop_reason: string | null }): T {
  if (!response.parsed_output) {
    throw new TutorError(
      response.stop_reason === "max_tokens"
        ? "The tutor ran out of room writing that. Try again."
        : "The tutor returned something that did not match the expected shape.",
    );
  }
  return response.parsed_output;
}

